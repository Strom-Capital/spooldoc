// Generates src/tables.generated.ts: EBCDIC single-byte decode tables.
// Runs the system iconv (macOS) over every byte value one at a time. Only run by hand
// when a code page is added; nothing at runtime or in CI calls iconv.
//   node scripts/gen-ebcdic.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const BASE = { 37: "IBM037", 273: "IBM273", 278: "IBM278", 500: "IBM500" };
// Euro variants: same table with the international currency sign replaced by the euro sign.
const EURO = { 1140: 37, 1141: 273, 1143: 278, 1148: 500 };

function decodeByte(charset, byte) {
  try {
    const out = execFileSync("iconv", ["-f", charset, "-t", "UTF-8"], {
      input: Buffer.from([byte]),
      stdio: ["pipe", "pipe", "ignore"],
    }).toString("utf8");
    return [...out].length === 1 ? out : "�";
  } catch {
    return "�";
  }
}

const tables = {};
for (const [cp, charset] of Object.entries(BASE)) {
  const chars = [];
  for (let b = 0; b < 256; b++) chars.push(decodeByte(charset, b));
  tables[cp] = chars;
}
// The EBCDIC control area (0x00-0x3F and 0xFF) is the same in every code page here, but the
// macOS iconv tables for 273 and 278 map it differently from 037 and 500 (and leave most of it
// undefined). Use the standard EBCDIC C0/C1 mapping from 037 for all of them.
for (const cp of Object.keys(BASE)) {
  for (let b = 0; b < 256; b++) {
    if (b < 0x40 || b === 0xff) tables[cp][b] = tables[37][b];
  }
}
for (const [cp, base] of Object.entries(EURO)) {
  const chars = [...tables[base]];
  const pos = chars.indexOf("¤");
  if (pos < 0) throw new Error(`no currency sign in ${base}`);
  chars[pos] = "€";
  tables[cp] = chars;
}

const lit = (chars) => JSON.stringify(chars.join("")).replace(/[\u007f-￿]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);
const lines = [
  "// Generated by scripts/gen-ebcdic.mjs from the system iconv. Do not edit by hand.",
  "// Each string has 256 UTF-16 code units: the character for EBCDIC byte 0x00 to 0xFF.",
  "",
  "/** Decode tables keyed by IBM code page number. */",
  "export const EBCDIC_TABLES: Readonly<Record<number, string>> = {",
  ...Object.keys(tables)
    .map(Number)
    .sort((a, b) => a - b)
    .map((cp) => `  ${cp}: ${lit(tables[cp])},`),
  "};",
  "",
];
const target = fileURLToPath(new URL("../src/tables.generated.ts", import.meta.url));
writeFileSync(target, lines.join("\n"));
for (const cp of Object.keys(tables)) {
  const t = tables[cp];
  if (t.length !== 256 || t.some((c) => c.length !== 1)) throw new Error(`bad table ${cp}`);
}
process.stdout.write(`wrote ${target}\n`);
