// Generates lib/server/carbone-skill.generated.ts: the Carbone Skill, the AI assistant's
// reference for Carbone's template syntax. Apache-2.0, from github.com/carboneio/carbone-skill
// at a pinned commit; its licence is in lib/server/carbone-skill.LICENSE. Only run by hand
// to move to a newer commit, then read the diff: the text goes into the model's instructions.
//   node scripts/gen-carbone-skill.mjs [commit]
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const REPO = "carboneio/carbone-skill";
const COMMIT = process.argv[2] ?? "25207b3f52b97872312eab997ee5c62cc5c9542d";
// SKILL.md, and the references that apply to the template kinds Spooldoc has: HTML and
// Word. A new kind adds its own: xlsx-tips for Excel, markdown-templates for Markdown.
const REFERENCES = [
  "html-templates",
  "docx-tips",
  "formatters",
  "loops-advanced",
  "aliases",
  "set-patterns",
  "practical-examples",
  "advanced-features",
  "in-template-options",
  "format-support",
];

async function read(path) {
  const url = `https://raw.githubusercontent.com/${REPO}/${COMMIT}/${path}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return (await response.text()).replace(/\r\n/g, "\n");
}

// The skill's front matter is for agent harnesses; the assistant gets the body.
const skill = (await read("carbone/SKILL.md")).replace(/^---\n[\s\S]*?\n---\n+/, "");
const references = {};
for (const name of REFERENCES) references[name] = await read(`carbone/references/${name}.md`);
const version = /^\s*version:\s*"?([^"\n]+)"?/m.exec(await read("carbone/SKILL.md"))?.[1] ?? "unknown";

const out = `// Generated by scripts/gen-carbone-skill.mjs. Do not edit.
//
// The Carbone Skill ${version}, https://github.com/${REPO} at commit ${COMMIT}.
// Copyright 2026 carboneio. Licensed under the Apache License, Version 2.0; see
// carbone-skill.LICENSE next to this file. Changed: the front matter of SKILL.md is left out.

/** Where the reference comes from, for the instructions and the docs. */
export const CARBONE_SKILL_SOURCE = ${JSON.stringify({ repository: `https://github.com/${REPO}`, commit: COMMIT, version, license: "Apache-2.0" })} as const;

/** SKILL.md without its front matter. */
export const CARBONE_SKILL = ${JSON.stringify(skill)};

/** The reference files for HTML and Word templates, by name (\`references/<name>.md\`). */
export const CARBONE_REFERENCES = ${JSON.stringify(references, null, 2)} as const;

export type CarboneReference = keyof typeof CARBONE_REFERENCES;
`;
writeFileSync(fileURLToPath(new URL("../lib/server/carbone-skill.generated.ts", import.meta.url)), out);
console.log(`Wrote the Carbone Skill ${version} (${COMMIT.slice(0, 7)}): SKILL.md and ${REFERENCES.length} references.`);
